//FUNCTION TO CREATE A CARD with innerHTML
function createProductCard(product) {
  const card = document.createElement("div");
  card.classList.add("productCard2");

  // store product info on the card
  card.dataset.id = product.id;
//ACTUAL CARD HTML THAT IS TIED TO CSS
  card.innerHTML = `
    <div class="FlexBadges">
      <div class="weightBadge2"><p>${product.weight}</p></div>
      <div class="priceBadge2"><p>${product.price.toFixed(2)} €</p></div>
    </div>

    <div class="FlexImageTextButton">
      <div class="bowlImage2">
        <img src="${product.image}" alt="${product.name}" />
      </div>

      <div class="headlineCard">
        <p>${product.name.replace(" ", "<br />")}</p>
        <button class="btn">Hinzufügen</button>
      </div>
    </div>
  `;

  return card;
}
